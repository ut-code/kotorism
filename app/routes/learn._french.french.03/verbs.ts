// ==== 派生ヘルパー ====
// フランス語の不規則動詞には、語幹や語尾のパターンを共有する「動詞ファミリー」が多い。
// 手入力のミスを避けるため、そうしたファミリーはベース動詞や共通パターンから機械的に導出する。

// 接頭辞を付けるだけで活用が作れる動詞（revenir=re+venir, apprendre=ap+prendre など）
function prefixed(
  base: IrregularVerb,
  prefix: string,
  id: string,
  infinitive: string,
  meaning: string,
  overrides: Partial<{ auxiliary: Auxiliary; futurStem: string }> = {},
): IrregularVerb {
  const p6 = (arr: SixForms): SixForms => arr.map((f) => prefix + f) as SixForms;
  return {
    id,
    infinitive,
    meaning,
    kind: "irregular",
    auxiliary: overrides.auxiliary ?? base.auxiliary,
    pastParticiple: prefix + base.pastParticiple,
    présent: p6(base.présent),
    subjonctifPrésent: p6(base.subjonctifPrésent),
    passéSimple: p6(base.passéSimple),
    futurStem: overrides.futurStem ?? prefix + base.futurStem,
    ...(base.imparfaitStem ? { imparfaitStem: prefix + base.imparfaitStem } : {}),
  };
}

// -crire型(écrire, décrire, inscrire, prescrire, souscrire, transcrire)
// stemは「〜cri」で終わる語幹（例: "écri", "décri", "inscri"）を渡す
function crireVerb(stem: string, id: string, infinitive: string, meaning: string): IrregularVerb {
  const longStem = stem + "v";
  return {
    id,
    infinitive,
    meaning,
    kind: "irregular",
    auxiliary: "avoir",
    pastParticiple: stem + "t",
    présent: [
      stem + "s",
      stem + "s",
      stem + "t",
      longStem + "ons",
      longStem + "ez",
      longStem + "ent",
    ],
    subjonctifPrésent: [
      longStem + "e",
      longStem + "es",
      longStem + "e",
      longStem + "ions",
      longStem + "iez",
      longStem + "ent",
    ],
    passéSimple: [
      longStem + "is",
      longStem + "is",
      longStem + "it",
      longStem + "îmes",
      longStem + "îtes",
      longStem + "irent",
    ],
    futurStem: stem + "r",
  };
}

