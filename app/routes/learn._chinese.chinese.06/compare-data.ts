// 日本語の漢字と、字体が異なる中国語の簡体字のペア。選択クイズ・手書き練習（./HanziCompare.tsx）で共通に使う。
// 収録範囲は、大学1年生が初修の第二外国語として学ぶ中国語のレベル（HSK1〜2級・中国語検定準4級〜4級程度、
// 初級教科書に出てくる語彙）で使う字に絞っている。
// 日本語と簡体字で同じ字形になるもの（例: 医・会・体）は、違いを学ぶ教材としては紛らわしいため載せない。
// 日本語の字・簡体字はそれぞれ一覧の中で重複させない（選択クイズで正解が一つに決まるようにするため）

export interface CharacterCompare {
  id: string;
  // 日本語で使われる字体（新字体）
  japanese: string;
  // 中国語の簡体字
  simplified: string;
  // 簡体字の拼音
  pinyin: string;
  // 日本語の音読み
  reading: string;
  // 日本語での意味
  meaning: string;
  // 簡体字を使った例（初級で習う単語・短い表現）
  example: { zh: string; pinyin: string; ja: string };
  // 字形の違いの説明（用意できているものだけ）
  difference?: string;
  // 日本語と中国語で意味・使い方がずれていて注意したい点
  note?: string;
}

type Extra = Pick<CharacterCompare, "difference" | "note">;

function pair(
  japanese: string,
  simplified: string,
  pinyin: string,
  reading: string,
  meaning: string,
  [zh, examplePinyin, ja]: [string, string, string],
  extra: Extra = {},
): CharacterCompare {
  return {
    id: japanese,
    japanese,
    simplified,
    pinyin,
    reading,
    meaning,
    example: { zh, pinyin: examplePinyin, ja },
    ...extra,
  };
}

